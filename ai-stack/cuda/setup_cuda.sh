#!/bin/bash
# BareCortex - CUDA Environment Setup Script
# Configures CUDA paths and environment variables

set -e

CUDA_INSTALL_DIR="/usr/local/cuda"
PROFILE_SCRIPT="/etc/profile.d/cuda.sh"

echo "=========================================="
echo "  BareCortex CUDA Environment Setup"
echo "=========================================="

# Check if CUDA is installed
if [ ! -d "${CUDA_INSTALL_DIR}" ]; then
    echo "[ERROR] CUDA not found at ${CUDA_INSTALL_DIR}"
    echo "Please install CUDA Toolkit first (see GLFS OpenRC Edition)."
    exit 1
fi

# Detect CUDA version (12.8+ ships version.json instead of version.txt)
CUDA_VERSION=$("$CUDA_INSTALL_DIR/bin/nvcc" --version 2>/dev/null | sed -n 's/.*release \([0-9.]*\),.*/\1/p' \
    || awk '/version/{print $3}' "$CUDA_INSTALL_DIR/version.json" 2>/dev/null \
    || awk '{print $3}' "$CUDA_INSTALL_DIR/version.txt" 2>/dev/null \
    || echo "unknown")
echo "[INFO] Detected CUDA installation: ${CUDA_INSTALL_DIR}"
echo "[INFO] CUDA version: ${CUDA_VERSION}"

# Create profile script for CUDA paths
cat > ${PROFILE_SCRIPT} << 'EOF'
# BareCortex CUDA Environment
# Automatically generated by setup_cuda.sh

export CUDA_HOME="/usr/local/cuda"
export PATH="${CUDA_HOME}/bin:${PATH}"
export LD_LIBRARY_PATH="${CUDA_HOME}/lib64:${LD_LIBRARY_PATH}"
export CPATH="${CUDA_HOME}/include:${CPATH}"
export LIBRARY_PATH="${CUDA_HOME}/lib64:${LIBRARY_PATH}"

# CUDA compiler flags (optional)
# export NVCC_PREPEND_FLAGS="-O3"

# NCCL configuration (for multi-GPU training)
export NCCL_DEBUG=WARN
# export NCCL_SOCKET_IFNAME=eth0
# export NCCL_IB_DISABLE=1
# export NCCL_P2P_LEVEL=NVL
EOF

chmod 644 ${PROFILE_SCRIPT}
echo "[OK] Created ${PROFILE_SCRIPT}"

# Create ldconfig entry for CUDA
echo "${CUDA_INSTALL_DIR}/lib64" > /etc/ld.so.conf.d/cuda.conf
ldconfig
echo "[OK] Updated ldconfig with CUDA library path"

# Verify nvcc is accessible
if command -v nvcc > /dev/null 2>&1; then
    echo "[OK] nvcc found: $(nvcc --version | grep release | awk '{print $6}')"
else
    echo "[WARN] nvcc not in current PATH. Run 'source ${PROFILE_SCRIPT}' or re-login."
fi

# Verify CUDA with deviceQuery if available
DEVICE_QUERY="${CUDA_INSTALL_DIR}/samples/1_Utilities/deviceQuery/deviceQuery"
if [ -x "${DEVICE_QUERY}" ]; then
    echo ""
    echo "[INFO] Running deviceQuery..."
    ${DEVICE_QUERY}
fi

echo ""
echo "=========================================="
echo "  CUDA environment setup complete!"
echo "  Run 'source ${PROFILE_SCRIPT}' or"
echo "  re-login to activate."
echo "=========================================="
